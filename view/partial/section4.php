        <h3>Megaera</h3>
        <p>Après sa première défaite, Mégère rejoint la Maison d’Hadès. Il est possible de la retrouver et peut être changée dans sa chambre, une fois vaincue lors d’un précédent run. Au début, elle se montre très froide envers Zagreus, mais au fil des discussions, elle semble se détendre. Une romance avec elle est possible si le joueur lui offre six cadeaux de nectar et neuf cadeaux d’ambroisie. Elle donne alors au joueur son souvenir, le gage de fidélité de Mégère. Elle n’est pas la seule furie à s’opposer à la fuite de Zagreus, lui et ses sœurs le remplacent.</p>
