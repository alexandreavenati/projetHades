        <h3>Thanatos</h3>
        <p>Thanatos apparaît parfois au début de rencontres régulières et met Zagreus au défi d'éliminer autant d'ennemis que possible avant qu'il ne puisse le faire. Il est stoïque et silencieux, mais profondément loyal envers son frère Zagreus. Il semble jaloux de l'attention que Zagreus reçoit de Mégère et il est sensible à la flatterie. Il a la particularité de pouvoir éliminer instantanément ses ennemis, grâce à ses pouvoirs divins. Il lui attribue un Centaure Cœur ou un objet de soin s’il l’humilie.</p>
