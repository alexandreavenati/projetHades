        <h3>Hades</h3>
        <p>Hades est sévère, sérieux et dévoué à son travail. Il est montré, dans les Souvenirs qui jouent avant certaines tentatives d'évasion, comme ayant été strict et souvent cruel avec Zagreus pendant son enfance. Il a employé Achille pour enseigner le combat à Zagreus et lui donner une "direction plus ferme dans la vie". Entre-temps, Hadès semble avoir laissé à Nyx une grande partie des soisns et de l'éducation de Zagreus.</p>
